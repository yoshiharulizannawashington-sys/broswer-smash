def key_pose(armature, frame, pose, loc=None):
    for bone_name, rotation in pose.items():
        bone = armature.pose.bones.get(bone_name)
        if not bone:
            continue
        bone.rotation_mode = 'XYZ'
        bone.rotation_euler = Euler(rotation, 'XYZ')
        bone.keyframe_insert('rotation_euler', frame=frame)
    if loc:
        bone = armature.pose.bones.get('Hips')
        bone.location = Vector(loc)
        bone.keyframe_insert('location', frame=frame)


def make_action(armature, name, keys, loop=True):
    armature.animation_data_create()
    action = bpy.data.actions.new(name)
    action.use_fake_user = True
    armature.animation_data.action = action
    for frame, pose, loc in keys:
        key_pose(armature, frame, pose, loc)
    for fcurve in action.fcurves:
        for point in fcurve.keyframe_points:
            point.interpolation = 'BEZIER'
    action.use_cyclic = loop
    return action


