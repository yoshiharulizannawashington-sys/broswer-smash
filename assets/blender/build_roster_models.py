def export(path):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=os.path.abspath(path),
        export_format='GLB',
        export_yup=True,
        export_apply=True,
        export_skins=True,
        export_animations=True,
        export_animation_mode='ACTIONS',
        export_bake_animation=True,
        export_force_sampling=True,
        export_frame_range=False,
        export_optimize_animation_size=True,
        export_anim_slide_to_zero=True,
        export_materials='EXPORT',
        use_selection=False,
    )
    return os.path.abspath(path)


def build_character(spec):
    reset_scene()
    mats = spec['palette']()
    bulk = spec.get('bulk', 1.0)
    shoulder = spec.get('shoulder', SHOULDER_X)
    height = spec.get('height', 1.0)

    parts = build_torso(mats, bulk=bulk, width=bulk, style=spec['style'])
    parts += build_limbs(mats, style=spec['style'], bulk=bulk, shoulder=shoulder)
    if spec['head'] == 'face':
        parts += build_face_head(mats, width=1.0)
        parts += build_hair(mats)
    elif spec['head'] == 'helmet':
        parts += build_helmet_head(mats)
    else:
        parts += build_mask_head(mats)

    weight_parts(parts)
    body = join_parts(parts, spec['body_name'])
    armature = build_armature(height=height, shoulder=shoulder)
    modifier = body.modifiers.new('Armature', 'ARMATURE')
    modifier.object = armature
    body.parent = armature
    build_animations(armature)
    bpy.context.view_layer.update()

    path = export(os.path.join(OUT_DIR, f"{spec['slug']}.glb"))
    triangles = sum(len(poly.vertices) - 2 for poly in body.data.polygons)
    materials = [mat.name for mat in body.data.materials]
    return {
        'slug': spec['slug'],
        'file': path,
        'bytes': os.path.getsize(path),
        'triangles': triangles,
        'vertices': len(body.data.vertices),
        'materials': materials,
        'bones': len(armature.data.bones),
        'weightedVertices': sum(1 for vertex in body.data.vertices if vertex.groups),
        'actions': [action.name for action in bpy.data.actions],
        'formSurfaces': [name for name in materials if name in ('fighter-hair', 'fighter-accent', 'arc-reactor')],
    }


def main():
    reports = []
    for spec in CHARACTERS:
        reports.append(build_character(spec))
    print('ROSTER_BUILD ' + json.dumps(reports))
    if REPORT:
        os.makedirs(os.path.dirname(os.path.abspath(REPORT)), exist_ok=True)
        with open(REPORT, 'w') as handle:
            json.dump(reports, handle, indent=2)


main()
