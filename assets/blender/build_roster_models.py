def build_armature(scale=1.0, shoulder=SHOULDER_X, hip=HIP_X, height=1.0):
    armature = bpy.data.armatures.new('rig')
    obj = bpy.data.objects.new('rig', armature)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode='EDIT')
    created = {}
    for name, head, tail, parent in bone_table(scale, shoulder, hip, height):
        bone = armature.edit_bones.new(name)
        bone.head = Vector(head)
        bone.tail = Vector(tail)
        bone.use_deform = True
        if parent:
            bone.parent = created[parent]
        created[name] = bone
    bpy.ops.object.mode_set(mode='OBJECT')
    return obj


def bone_for_part(name):
    side_match = re.search(r'-(L|R)(?:-|$)', name)
    side = side_match.group(1) if side_match else None
    if name.startswith(('head', 'eye', 'iris', 'brow', 'ear', 'nose', 'mouth', 'hair', 'fringe',
                        'helmet', 'faceplate', 'crest', 'mask', 'lens', 'brow-trim')):
        return 'Head'
    if name == 'neck':
        return 'Neck'
    if name.startswith(('skirt', 'sash', 'belt', 'hip-plate')):
        return 'Hips'
    if name.startswith(('torso', 'gi-jacket', 'lapel', 'collar', 'shoulder', 'chest-plate',
                        'collar-plate', 'ab-plate', 'back-plate', 'thruster', 'reactor',
                        'arc-reactor', 'sternum', 'chest-panel', 'rib-panel', 'suit-seam',
                        'spider-emblem', 'emblem-leg', 'pauldron')):
        return 'Chest'
    if name.startswith('upperarm'):
        return f'{side}Arm'
    if name.startswith(('forearm', 'wrap', 'bracer')):
        return f'{side}ForeArm'
    if name.startswith(('palm', 'finger', 'thumb', 'repulsor-palm')):
        return f'{side}Hand'
    if name.startswith('thigh'):
        return f'{side}UpLeg'
    if name.startswith(('knee', 'shin')):
        return f'{side}Leg'
    if name.startswith(('boot', 'toe', 'sole')):
        return f'{side}Foot'
    return 'Hips'


def weight_parts(parts):
    for part in parts:
        group = part.vertex_groups.new(name=bone_for_part(part.name))
        group.add([vertex.index for vertex in part.data.vertices], 1.0, 'REPLACE')


def join_parts(parts, name):
    bpy.ops.object.select_all(action='DESELECT')
    for part in parts:
        part.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    bpy.ops.object.join()
    body = bpy.context.object
    body.name = name
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.mesh.remove_doubles(threshold=0.0008)
    bpy.ops.mesh.normals_make_consistent(inside=False)
    bpy.ops.object.mode_set(mode='OBJECT')
    return body


