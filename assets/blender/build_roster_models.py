# Build the three flagship fighters as real skinned GLBs.
#
#   bash scripts/blender.sh -b --python assets/blender/build_roster_models.py -- --out-dir public/models/characters/original
#
# What these are, stated plainly: ORIGINAL stylised fighters authored by this script. They are
# not the licensed Goku / Iron Man / Iron Spider character models - those source files have never
# been supplied to this repository, and downloading an unlicensed copy is not allowed. They are
# recognisably in the same archetypes (anime martial artist with a gi and spiked hair; red-and-gold
# armoured avenger with a chest reactor; red-and-gold spider suit with an articulated leg rig the
# game adds at runtime), and every vertex here is generated by this file.
#
# Each character gets:
#   * lofted anatomy with its own proportions (bulk, shoulder width, head scale),
#   * a distinct head (face / helmet with faceplate / masked lenses),
#   * layered clothing or armour appropriate to the archetype,
#   * separate PBR materials, including the surface names the transformation system looks for
#     (`fighter-hair`, `fighter-accent`, `arc-reactor`),
#   * a 19-bone humanoid armature with rigid per-part skin weights,
#   * eight 60 fps actions named after the game's clip ids.
#
# Verified afterwards by scripts/inspect-character-glb.mjs.

