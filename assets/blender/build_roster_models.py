# --------------------------------------------------------------------------- scene helpers


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.fps = 60
    scene.frame_start = 1
    scene.frame_end = 60


def make_material(name, color, metallic=0.0, roughness=0.6, emission=None, emission_strength=1.0):
    # A name that already exists would be reused by Blender across characters in one session, so
    # every character's palette is created fresh after a scene reset; assert that here.
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get('Principled BSDF')
    bsdf.inputs['Base Color'].default_value = (*color, 1.0)
    bsdf.inputs['Metallic'].default_value = metallic
    bsdf.inputs['Roughness'].default_value = roughness
    if emission:
        bsdf.inputs['Emission Color'].default_value = (*emission, 1.0)
        bsdf.inputs['Emission Strength'].default_value = emission_strength
    return mat


def mesh_object(name, verts, faces, material, smooth=True):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    obj.data.materials.append(material)
    bpy.context.collection.objects.link(obj)
    for poly in mesh.polygons:
        poly.use_smooth = smooth
    return obj


def loft(name, sections, material, segments=20, cap_start=True, cap_end=True, smooth=True):
    verts, faces = [], []
    for section in sections:
        cx, cy, cz = section.get('x', 0.0), section.get('y', 0.0), section.get('z', 0.0)
        rx = section['rx']
        rz = section.get('rz', rx)
        for i in range(segments):
            angle = (i / segments) * TAU
            dx = math.cos(angle) * rx
            dz = math.sin(angle) * rz
            if dz > 0 and section.get('front'):
                dz *= section['front']
            if dz < 0 and section.get('back'):
                dz *= section['back']
            verts.append((cx + dx, cy, cz + dz))
    for ring in range(len(sections) - 1):
        for i in range(segments):
            a = ring * segments + i
            b = ring * segments + ((i + 1) % segments)
            c = (ring + 1) * segments + i
            d = (ring + 1) * segments + ((i + 1) % segments)
            faces.append((a, b, d, c))
    if cap_start:
        centre = len(verts)
        first = sections[0]
        verts.append((first.get('x', 0.0), first.get('y', 0.0), first.get('z', 0.0)))
        for i in range(segments):
            faces.append((centre, (i + 1) % segments, i))
    if cap_end:
        base = (len(sections) - 1) * segments
        centre = len(verts)
        last = sections[-1]
        verts.append((last.get('x', 0.0), last.get('y', 0.0), last.get('z', 0.0)))
        for i in range(segments):
            faces.append((centre, base + i, base + (i + 1) % segments))
    return mesh_object(name, verts, faces, material, smooth)


def box(name, size, location, material, rotation=(0, 0, 0)):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=location, rotation=rotation)
    obj = bpy.context.object
    obj.name = name
    obj.scale = (size[0], size[1], size[2])
    obj.data.materials.append(material)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    return obj


def sphere(name, radius, location, material, scale=(1, 1, 1), segments=20, rings=12):
    bpy.ops.mesh.primitive_uv_sphere_add(radius=radius, segments=segments, ring_count=rings, location=location)
    obj = bpy.context.object
    obj.name = name
    obj.scale = scale
    obj.data.materials.append(material)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    for poly in obj.data.polygons:
        poly.use_smooth = True
    return obj


def cone(name, radius, depth, location, material, rotation=(0, 0, 0), vertices=8):
    bpy.ops.mesh.primitive_cone_add(radius1=radius, radius2=0.0, depth=depth, vertices=vertices,
                                    location=location, rotation=rotation)
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(material)
    return obj


def torus(name, major, minor, location, material, rotation=(0, 0, 0)):
    bpy.ops.mesh.primitive_torus_add(major_radius=major, minor_radius=minor, major_segments=22,
                                     minor_segments=8, location=location, rotation=rotation)
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(material)
    for poly in obj.data.polygons:
        poly.use_smooth = True
    return obj


