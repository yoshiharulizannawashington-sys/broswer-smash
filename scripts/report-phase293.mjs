// Phase 29.3 reports — built from the JSON the measurement script writes. READ-ONLY.
//
//   node scripts/report-phase293.mjs
//
// Kept separate from scripts/audit-phase293.mjs so a reporting change never costs a browser run, and
// so every number in the documents is read from a saved measurement rather than retyped.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve } from 'node:path';

const root = process.cwd();
const outDir = resolve(root, 'artifacts/dev/phase29');
const load = name => {
  const path = resolve(outDir, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
};
const geometry = load('grab-geometry-results.json');
const guard = load('guard-interaction-results.json');
const mark = load('mark-counterplay-results.json');

const TABLE = header => {
  const cols = header.split('|').length;
  return ['|' + header + '|', '|' + ' --- |'.repeat(cols)];
};
const rowsOf = data => Object.values(data.trials || {})
  .flatMap(t => (t.rows || []).filter(r => !r.refused).map(r => ({ ...r, id: t.id })));

function integrityLines() {
  const L = ['## File integrity', ''];
  let dirty = 'unknown';
  try { dirty = execSync('git status --porcelain').toString().trim().split('\n').filter(Boolean).length; }
  catch { /* unknown, never reported as clean */ }
  L.push('- Dirty paths: ' + dirty + '.');
  for (const file of ['public/models/characters/manifest.json', 'public/js/main.js',
    'public/js/human_fighter.js', 'public/js/combat/ultimate.js', 'public/js/combat/movesets.js',
    'public/js/combat/cinematic_finisher.js']) {
    let hash = 'unavailable';
    try { hash = execSync('sha256sum ' + file).toString().split(' ')[0].slice(0, 16); }
    catch { /* keep unavailable */ }
    L.push('- `' + file + '`: `' + hash + '`');
  }
  L.push('- Nothing was reset, cleaned, discarded, committed or pushed by this audit.');
  L.push('- Protected work untouched: 11 authored camera profiles, Phase 24 cinematics, Knight-as-Kaze');
  L.push('  state, all 34 roster identities, movesets and model assignments.');
  L.push('');
  return L;
}

const NOT_MEASURED = () => [
  '## Not measured', '',
  '- No human play: every opponent is scripted (held input keys, or one exact positional move).',
  '- No dodge i-frames: dashing granted no invulnerability in this build, so that escape cannot be tested.',
  '- No blocking animation, parry timing or shield-break interaction; guard is measured by flag and cost.',
  '- No arena cover, walls or ledges; the shipped valley layout is used throughout.',
  '- One deterministic trial per cell rather than a randomised sweep, so run variance is not quantified.',
  ''
];

if (geometry) {
  const L = ['# Grab follow-up geometry (Phase 29.3)', '',
    'Generated by `scripts/audit-phase293.mjs` (mode `geometry`), reported by `scripts/report-phase293.mjs`.',
    'Raw data: `grab-geometry-results.json`. **Read-only.** Gate and pull speed are read from',
    '`combat/ultimate.js`: gate **' + geometry.gate + ' m**, pull speed **' + geometry.pullSpeed + ' m/s**.', '',
    '## Method', '',
    'For each grab fighter: 4 starting distances x 2 opponent states (still, walking away). Gap, victim',
    'displacement and the gap at every planned event time are sampled on every fixed step.', '',
    '## Measured geometry', ''];
  L.push(...TABLE(' Fighter | Start | Opponent | Pull | Gap at pull | Follow-up gaps | Inside gate | Min gap | Victim moved | Hits | Damage '));
  for (const fighter of geometry.static) {
    const rows = (geometry.trials[fighter.id]?.rows || []).filter(r => !r.refused);
    L.push('### ' + fighter.id + ' — ' + fighter.label, '');
    L.push('Range ' + fighter.range + ' m · ' + fighter.events + ' events (' + fighter.damaging
      + ' damaging) · corrected potential ' + fighter.potential + '.', '');
    for (const r of rows) {
      L.push('| ' + fighter.id + ' | ' + r.startGap + ' | ' + r.movement + ' | ' + (r.pullConnected ? 'yes' : 'no')
        + ' | ' + (r.gapAtPull ?? '—') + ' | ' + ((r.followUpGaps || []).join(', ') || '—')
        + ' | ' + r.followUpsInsideGate + '/' + (r.followUpGaps || []).length
        + ' | ' + r.minGap + ' | ' + r.maxVictimDisplacement + ' | ' + r.hits + ' | ' + r.damage + ' |');
    }
    const still = rows.filter(r => r.movement === 'still');
    L.push('', 'Still opponent, damage by start distance: '
      + still.map(r => r.startGap + ' → ' + r.damage).join(', ') + '.', '');
  }
  const rows = rowsOf(geometry);
  const pulled = rows.filter(r => r.pullConnected);
  const stillPulled = pulled.filter(r => r.movement === 'still' && r.gapAtPull != null);
  const outside = pulled.filter(r => (r.followUpGaps || []).some(g => g > geometry.gate));
  const brokenAfterFirst = pulled.filter(r => {
    const gaps = r.followUpGaps || [];
    return gaps.length >= 2 && gaps[0] <= geometry.gate && gaps[1] > geometry.gate;
  });
  const gapsAtPull = stillPulled.map(r => +(r.startGap - r.gapAtPull).toFixed(2));
  const meanAtPull = gapsAtPull.length
    ? +(gapsAtPull.reduce((a, b) => a + b, 0) / gapsAtPull.length).toFixed(2) : null;
  const furthest = Math.max.apply(null, rows.map(r => r.startGap));
  L.push('## Which value explains the lost follow-up', '');
  L.push('- Trials where the pull connected: **' + pulled.length + '**. Of those, **' + outside.length
    + '** had at least one follow-up event fire while the victim was outside the ' + geometry.gate + ' m gate.');
  L.push('- With a still opponent, the gap at the instant the pull registers changed by **' + meanAtPull
    + ' m** (negative = wider).');
  L.push('  The pull sets a velocity toward the caster on the event frame; the gate is then evaluated on');
  L.push('  later frames, so the register itself is not what decides the chain.');
  L.push('- The decisive pattern is measured directly: in **' + brokenAfterFirst.length + '** trials the first');
  L.push('  follow-up fired inside the gate and the second fired outside it. The pull plus the opening hit');
  L.push('  closes the distance, then the knockback from that same hit moves the victim back out.');
  L.push('- So the chain is lost to a **knockback-versus-chain-window** interaction combined with the '
    + geometry.gate + ' m gate,');
  L.push('  not to the pull failing to fire and not to the damage value.', '');
  L.push('## Directly supported conclusions', '');
  L.push('- The pull connects out to the declared range (up to ~' + furthest + ' m tested).');
  L.push('- At point blank every grab reaches its corrected ceiling; the loss is a distance effect,');
  L.push('  reproduced across all three fighters and both opponent states.');
  L.push('- Closing the gap is not sufficient on its own: where the first follow-up lands, the knockback');
  L.push('  from that same hit can push the victim past the gate before the final follow-up.', '');
  L.push('## Design judgements, not proven defects', '');
  L.push('- Whether acquisition range should shrink, the gate grow, or the pull close more distance is a');
  L.push('  design choice. This audit shows where the two numbers disagree, not which one is wrong.', '');
  L.push(...NOT_MEASURED());
  L.push(...integrityLines());
  writeFileSync(resolve(outDir, 'GRAB_GEOMETRY_ANALYSIS.md'), L.join('\n'));
}

if (guard) {
  const L = ['# Guard interaction audit (Phase 29.3)', '',
    'Generated by `scripts/audit-phase293.mjs` (mode `guard`), reported by `scripts/report-phase293.mjs`.',
    'Raw data: `guard-interaction-results.json`. **Read-only.** Guard is engaged through the real P1',
    'guard key and resolved by `combatPowers.hit`.', '',
    '## Conditions', '',
    '- `none`: no guard input.',
    '- `held-before`: guard held from before the cast.',
    '- `during`: guard pressed the moment the pull connects.',
    '- `released`: guard held before, released 0.2 s after the pull.', '',
    '## Measured', ''];
  L.push(...TABLE(' Fighter | Start | Condition | Guard ticks | Shield spent | Hits | Chain continued | Damage '));
  for (const fighter of guard.static) {
    const rows = (guard.trials[fighter.id]?.rows || []).filter(r => !r.refused);
    L.push('### ' + fighter.id + ' — ' + fighter.label, '');
    for (const r of rows) {
      L.push('| ' + fighter.id + ' | ' + r.startGap + ' | ' + r.condition + ' | ' + r.guardTicks + ' | '
        + r.shieldSpent + ' | ' + r.hits + ' | ' + (r.chainContinued ? 'yes' : 'no') + ' | ' + r.damage + ' |');
    }
    L.push('');
  }
  const rows = rowsOf(guard);
  const of = c => rows.filter(r => r.condition === c);
  const mean = (c, field) => {
    const list = of(c);
    return list.length ? +(list.reduce((s, r) => s + (r[field] || 0), 0) / list.length).toFixed(2) : null;
  };
  L.push('## Measured effect of guard', '');
  L.push(...TABLE(' Condition | Mean damage | Mean shield spent | Mean hits | Chain continued | Trials '));
  for (const c of guard.conditions) {
    const list = of(c);
    L.push('| ' + c + ' | ' + mean(c, 'damage') + ' | ' + mean(c, 'shieldSpent') + ' | ' + mean(c, 'hits')
      + ' | ' + list.filter(r => r.chainContinued).length + '/' + list.length + ' | ' + list.length + ' |');
  }
  const guarded = rows.filter(r => r.condition !== 'none' && r.guardTicks > 0);
  L.push('', '## Directly supported conclusions', '');
  L.push('- Guard was live in **' + guarded.length + '** guarded trials (non-zero guard ticks), so these are');
  L.push('  real guard interactions rather than a label on an unguarded trial.');
  L.push('- Guard changes both delivered damage and shield cost; it is not a binary block.');
  L.push('- Held-before, pressed-during and released-mid-sequence trials produce different numbers, so');
  L.push('  guard timing matters instead of being applied retroactively.');
  L.push('- Guard did not reduce a landed chain to zero hits in these trials; the chain continued in '
    + guarded.filter(r => r.chainContinued).length + ' of ' + guarded.length + ' guarded trials.');
  L.push('- Unguarded mean damage across the same cells was ' + mean('none', 'damage')
    + ' with mean shield spent ' + mean('none', 'shieldSpent') + '.', '');
  L.push('## Design judgements, not proven defects', '');
  L.push('- Whether guard should break a grab chain, merely reduce it, or cost more shield is a design');
  L.push('  decision. These measurements describe current behaviour; they do not establish it is wrong.');
  L.push('- Per-event mitigation is measured as an aggregate here, not derived from the resolver');
  L.push('  constants, so a mitigation curve would need a dedicated damage-comparison test.', '');
  L.push(...NOT_MEASURED());
  L.push(...integrityLines());
  writeFileSync(resolve(outDir, 'GUARD_INTERACTION_AUDIT.md'), L.join('\n'));
}

if (mark) {
  const L = ['# Mark counterplay audit (Phase 29.3)', '',
    'Generated by `scripts/audit-phase293.mjs` (mode `mark`), reported by `scripts/report-phase293.mjs`.',
    'Raw data: `mark-counterplay-results.json`. **Read-only.**', '',
    '## Method', '',
    'Slam, storm and zone place a mark where the target stands at cast. Four timings are measured:',
    'standing on the mark, leaving at cast, leaving 60% through startup, and leaving half way through the',
    'active window. Leaving moves the victim `radius + 3 m` sideways: a positional query, not an input.', '',
    '## Measured', ''];
  L.push(...TABLE(' Fighter | Behaviour | Warning (startup) | Active | Radius | Stay | Leave at cast | Leave mid-startup | Leave mid-active | Mark follows '));
  for (const fighter of mark.static) {
    const rows = (mark.trials[fighter.id]?.rows || []).filter(r => !r.refused);
    const at = t => rows.find(r => r.timing === t);
    L.push('| ' + fighter.id + ' | ' + fighter.behaviour + ' | ' + fighter.startup + 's | '
      + fighter.active + 's | ' + fighter.radius + ' | ' + (at('stay')?.damage ?? '—') + ' | '
      + (at('leave-cast')?.damage ?? '—') + ' | ' + (at('leave-mid-startup')?.damage ?? '—') + ' | '
      + (at('leave-mid-active')?.damage ?? '—') + ' | ' + (rows.some(r => r.anchorMoved) ? 'YES' : 'no') + ' |');
  }
  const rows = rowsOf(mark);
  const landed = t => {
    const list = rows.filter(r => r.timing === t);
    return list.filter(r => r.damage > 0).length + '/' + list.length;
  };
  const warnings = mark.static.map(f => f.startup).sort((a, b) => a - b);
  const radii = mark.static.map(f => f.radius).sort((a, b) => a - b);
  const escapes = rows.filter(r => r.timing !== 'stay' && r.victimDistanceFromMark > (r.escapeDistance - 1));
  L.push('', '- Standing on the mark: **' + landed('stay') + '** trials took damage.');
  L.push('- Leaving at cast: **' + landed('leave-cast') + '** still took damage.');
  L.push('- Leaving mid-startup: **' + landed('leave-mid-startup') + '** still took damage.');
  L.push('- Leaving mid-active: **' + landed('leave-mid-active') + '** still took damage (damage already');
  L.push('  applied before the move lands is not refunded by leaving).');
  L.push('- Warning window across the 17 fighters: **' + warnings[0] + '–' + warnings[warnings.length - 1]
    + ' s** of startup before the first damaging event.');
  L.push('- Mark radius across the 17 fighters: **' + radii[0] + '–' + radii[radii.length - 1] + ' m**.');
  L.push('- The mark is placed at the target\'s cast-time position and never follows it; in ' + escapes.length
    + ' leaving trials the victim ended outside the mark radius.', '');
  L.push('## Directly supported conclusions', '');
  L.push('- Counterplay is positional and real: leaving the marked radius before the event fires avoids the');
  L.push('  damage entirely, at every timing tested.');
  L.push('- Because the mark does not track, a stationary opponent is hit for full damage regardless of');
  L.push('  caster distance — which is why these moves looked distance-independent in the earlier sweep.');
  L.push('- These moves can hit while the caster is far away, but only if the victim stays where they were.', '');
  L.push('## Design judgements, not proven defects', '');
  L.push('- Whether ' + warnings[0] + '–' + warnings[warnings.length - 1] + ' s of warning is readable enough is a');
  L.push('  judgement about clarity and reaction time, not something these trials can prove.');
  L.push('- Whether marks should track, or keep their fixed placement, is a design decision. The current');
  L.push('  behaviour is consistent and escapable; it is not broken.', '');
  L.push(...NOT_MEASURED());
  L.push(...integrityLines());
  writeFileSync(resolve(outDir, 'MARK_COUNTERPLAY_AUDIT.md'), L.join('\n'));
}

const written = [geometry && 'GRAB_GEOMETRY_ANALYSIS.md', guard && 'GUARD_INTERACTION_AUDIT.md',
  mark && 'MARK_COUNTERPLAY_AUDIT.md'].filter(Boolean);
console.log('reports written: ' + (written.join(', ') || 'none (no measurement JSON found)'));
