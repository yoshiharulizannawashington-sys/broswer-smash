// Which animation path does each roster fighter actually use?
//
// The roster is three populations, not one, and saying "the fighters animate" hides that:
//   authored   the identity has hand-keyed attack motions (anim/attack_motions_*.js) that the
//              controller compiles into clips for its own rig
//   baked      the GLB ships clips, and the state machine/controller drives them
//   procedural the fighter has no assets; a code-authored pose writer moves its joints every frame
//
// This reads the real files rather than the docs, so the answer cannot drift from the build.
//
//   node scripts/report-animation-paths.mjs [--json] [--write]
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { AUTHORED_ATTACK_SLOTS, SPECIAL_CLIP_BY_IDENTITY } from '../public/js/anim/animation_manifest.js';

const rosterDir = 'public/models/characters/roster';
const onlyJson = process.argv.includes('--json');
const write = process.argv.includes('--write');

function readGlbAnimations(buffer) {
  if (buffer.length < 20) return [];
  const jsonLength = buffer.readUInt32LE(12);
  const json = JSON.parse(buffer.subarray(20, 20 + jsonLength).toString('utf8'));
  return (json.animations || []).map(animation => animation.name || 'unnamed');
}

const files = await readdir(rosterDir).catch(() => []);
const bodies = new Map();
for (const file of files.filter(name => name.endsWith('.glb'))) {
  const slug = file.replace(/\.glb$/, '');
  const animations = readGlbAnimations(await readFile(`${rosterDir}/${file}`));
  bodies.set(slug, { file, animations });
}

const rosterSource = await readFile('public/js/main.js', 'utf8');
const rosterBlock = rosterSource.slice(rosterSource.indexOf('const allRoster=['), rosterSource.indexOf('window.characterRosters='));
const names = [...rosterBlock.matchAll(/\["([^"]+)","([a-z]+)"\]/g)].map(([, name, archetype]) => ({ name, archetype }));

const rows = names.map(({ name, archetype }) => {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  const body = bodies.get(slug);
  const authored = AUTHORED_ATTACK_SLOTS[slug] || null;
  const authoredSlots = authored ? Object.entries(authored).map(([key, value]) => `${key}→${value}`) : [];
  let path;
  if (authored) path = 'authored attack motions';
  else if (body?.animations.length) path = 'baked clips';
  else path = 'procedural pose writer';
  return {
    fighter: name,
    slug,
    archetype,
    path,
    asset: body ? body.file : 'none',
    bakedClips: body ? body.animations.length : 0,
    authoredSlots,
    signature: SPECIAL_CLIP_BY_IDENTITY[slug] || (authored?.special ? `authored_${authored.special}` : 'special_attack (shared)')
  };
});

const lines = [
  '# Animation path per fighter',
  '',
  'Generated by `node scripts/report-animation-paths.mjs --write` from the exported GLBs and the',
  'animation manifest, so it reports the build rather than an intention.',
  '',
  'What each path can and cannot do:',
  '',
  '- **authored attack motions** — the identity has hand-keyed attack motion in',
  '  `public/js/anim/attack_motions_*.js`. `authoredAttackSlotsFor()` compiles those keyframes into',
  '  clips for the rig the fighter actually owns (`anim/attack_clips.js`), so every attack, the',
  '  signature and the kit abilities play that fighter’s own poses. This cannot be picked up by another',
  '  fighter: the motions are per identity and the clips are compiled per rig.',
  '- **baked clips** — the GLB ships its own named clips. Locomotion and reactions come from those',
  '  clips through the state machine/controller; attacks additionally receive the shared authored',
  '  motion overlay (`anim/attack_animator.js`), which is the generic punch/kick set, not an identity',
  '  set. A baked fighter therefore *does* animate every attack, but with the shared motions.',
  '- **procedural pose writer** — the fighter has no rigged asset. `fighter3D.js`',
  '  (`updateProceduralPose`) writes joint rotations every frame from code, including locomotion,',
  '  guard, dodge, hitstun and an attack pose. It cannot play an authored motion clip: there is no',
  '  skeleton to bind one to. Its attacks are posture changes, not authored keyframes.',
  '',
  '| Fighter | Path | Baked clips in GLB | Authored slots | Signature clip |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(row => `| ${row.fighter} | ${row.path} | ${row.bakedClips} | ${row.authoredSlots.length ? row.authoredSlots.join(', ') : '—'} | ${row.signature} |`)
];

const summary = rows.reduce((acc, row) => ((acc[row.path] = (acc[row.path] || 0) + 1), acc), {});
console.log(JSON.stringify({ summary, fighters: rows.length }, null, 2));
if (!onlyJson) for (const row of rows) console.log(`${row.path.padEnd(24)} ${row.fighter}${row.authoredSlots.length ? ' (' + row.authoredSlots.join(', ') + ')' : ''}`);
if (write) {
  await writeFile('docs/ANIMATION_FALLBACK_REPORT.md', lines.join('\n') + '\n');
  console.log('wrote docs/ANIMATION_FALLBACK_REPORT.md');
}
