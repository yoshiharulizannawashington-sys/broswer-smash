// Phase 29.3 priority 1 — corrected ultimate balance table. READ-ONLY.
//
//   node scripts/build-corrected-balance.mjs
//
// The Phase 29 baseline (BALANCE_AUDIT.md) counted `hits` damaging events for every behaviour. In
// `BEHAVIOURS.grab`, event 0 is the pull and deals no damage, so the grab ceiling was overstated by
// one hit. This rebuilds the table from the same real data with that corrected, and re-expresses the
// measured casts from `balance-measured.jsonl` against the corrected ceiling.
//
// The old report is deliberately left untouched as historical evidence; this one cites it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { MOVESETS } from '../public/js/combat/movesets.js';

const root = process.cwd();
const outDir = resolve(root, 'artifacts/dev/phase29');

const ultimateSource = readFileSync(resolve(root, 'public/js/combat/ultimate.js'), 'utf8');
const defaultsLiteral = ultimateSource.match(/const DEFAULTS = Object\.freeze\((\{[\s\S]*?\})\);/)?.[1];
if (!defaultsLiteral) throw new Error('could not read DEFAULTS from combat/ultimate.js');
const DEFAULTS = new Function(`return ${defaultsLiteral};`)();

const NON_DAMAGING = { grab: 1 }; // the pull is event 0 and deals nothing

function fold(id, moveset) {
  const raw = moveset.ultimate || {};
  const d = { ...(DEFAULTS[raw.behaviour] || {}), ...raw };
  const events = d.hits ?? d.ticks ?? 1;
  const nonDamaging = NON_DAMAGING[d.behaviour] || 0;
  const damaging = Math.max(0, events - nonDamaging);
  let potential, guaranteed;
  if (d.behaviour === 'zone') {
    potential = d.damage * (events - 1) + d.damage * 1.6;
    guaranteed = d.damage * events;
  } else if (d.behaviour === 'beam') {
    potential = d.damage; guaranteed = d.damage * .55;
  } else if (d.behaviour === 'slam') {
    potential = d.damage; guaranteed = d.damage * .4;
  } else {
    potential = d.damage * damaging; guaranteed = 0;
  }
  return {
    id, label: d.label, behaviour: d.behaviour,
    damage: d.damage, events, nonDamaging, damaging,
    potential: +potential.toFixed(2), guaranteed: +guaranteed.toFixed(2),
    // What the Phase 29 baseline used. It already applied the zone 1.6x final tick, so the ONLY
    // fighters whose ceiling changes are the grabs, where the baseline counted the pull as damage.
    previousPotential: +(d.behaviour === 'grab' ? d.damage * events : potential).toFixed(2),
    startup: d.startup, active: d.active, recovery: d.recovery,
    total: +(d.startup + d.active + d.recovery).toFixed(2),
    exposure: +(d.startup + d.active).toFixed(2),
    range: d.range ?? null, radius: d.radius ?? null,
    kbs: d.kbs ?? null, launchY: d.launchY ?? null, stun: d.stun ?? null
  };
}

const rows = Object.entries(MOVESETS).map(([id, v]) => fold(id, v));

// Measured casts from the Phase 29 sweep, re-expressed against the corrected ceiling.
const measuredPath = resolve(outDir, 'balance-measured.jsonl');
const measured = {};
if (existsSync(measuredPath)) {
  for (const line of readFileSync(measuredPath, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const entry = JSON.parse(line);
    const casts = (entry.casts || []).filter(c => !c.refused);
    measured[entry.id] = {
      casts: casts.length,
      effectiveDamage: casts.length
        ? +(casts.reduce((s, c) => s + (c.damage || 0), 0) / casts.length).toFixed(2) : null,
      pointBlank: casts.find(c => c.name === 'point-blank')?.damage ?? null,
      mid: casts.find(c => c.name === 'mid-reach')?.damage ?? null,
      far: casts.find(c => c.name === 'past-reach')?.damage ?? null
    };
  }
}
for (const row of rows) {
  const m = measured[row.id];
  row.measured = m || null;
  row.deliveredShare = m?.effectiveDamage != null
    ? +((m.effectiveDamage / Math.max(.01, row.potential)) * 100).toFixed(0) : null;
  row.previousShare = m?.effectiveDamage != null
    ? +((m.effectiveDamage / Math.max(.01, row.previousPotential)) * 100).toFixed(0) : null;
}

const families = {};
for (const row of rows) (families[row.behaviour] ||= []).push(row);
const median = list => {
  const s = [...list].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};
for (const [, list] of Object.entries(families)) {
  const p = median(list.map(r => r.potential));
  const prev = median(list.map(r => r.previousPotential));
  for (const row of list) {
    row.familyMedian = +p.toFixed(2);
    row.familyMedianPrevious = +prev.toFixed(2);
    row.vsFamily = +(row.potential / p).toFixed(2);
    row.outlier = row.vsFamily >= 1.35 || row.vsFamily <= .74;
  }
}

const L = [];
L.push('# Ultimate balance — corrected table (Phase 29.3)', '',
  'Generated by `scripts/build-corrected-balance.mjs` from `combat/movesets.js` folded with the real',
  '`combat/ultimate.js` defaults, plus the live casts recorded in `balance-measured.jsonl`.',
  '**Read-only: no damage, cooldown, meter or moveset value was changed.**', '',
  'Historical evidence is preserved unchanged in `BALANCE_AUDIT.md`; this file supersedes only its',
  'grab ceiling, and says so explicitly below.', '',
  '## 1. Methodology change and why', '',
  'The Phase 29 baseline defined potential as `damage x events`. For `grab`, event 0 is the pull and',
  'deals **no damage** (`BEHAVIOURS.grab` returns after applying pull velocity), so the ceiling is',
  '`damage x (hits - 1)`. The correction applies to three fighters and to no other behaviour.',
  '', '| Fighter | Old ceiling | Corrected ceiling | Difference |', '| --- | --- | --- | --- |');
for (const row of rows.filter(r => r.previousPotential !== r.potential)) {
  L.push(`| ${row.id} | ${row.previousPotential} | ${row.potential} | ${(row.potential - row.previousPotential).toFixed(2)} |`);
}
L.push('', 'Zone ceilings are unchanged here because the baseline already applied the 1.6x final tick; only',
  'the grab row changed. Everything else in the previous table stands: same definitions, same defaults, same',
  'measured casts. Only the grab ceiling and every number derived from it are restated.', '',
  '## 2. Corrected matrix (all 34)', '',
  'Potential = every damaging event landing at its ceiling. Guaranteed = the floor when the target',
  'co-operates (beam 55% falloff floor, slam 40% floor, zone full ticks, contact moves 0 because each',
  'event can miss). Exposure = startup + active, with no invulnerability granted.', '',
  '| Identity | Behaviour | Damage/event | Damaging events | Potential | Guaranteed | Startup | Active | Recovery | Exposure |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const r of rows) {
  L.push(`| ${r.id} | ${r.behaviour} | ${r.damage} | ${r.damaging} | ${r.potential} | ${r.guaranteed} | `
    + `${r.startup} | ${r.active} | ${r.recovery} | ${r.exposure} |`);
}

L.push('', '## 3. Measured delivery, corrected', '',
  '`delivered %` divides the Phase 29 measured effective damage by the **corrected** ceiling;',
  '`old %` is the same measurement against the old ceiling, which is what produced the misleading',
  '33% grab figure.', '',
  '| Identity | Point blank | Mid reach | Past reach | Effective | Delivered % | Old % |',
  '| --- | --- | --- | --- | --- | --- | --- |');
for (const r of rows) {
  const m = r.measured;
  L.push(`| ${r.id} | ${m?.pointBlank ?? '—'} | ${m?.mid ?? '—'} | ${m?.far ?? '—'} | `
    + `${m?.effectiveDamage ?? '—'} | ${r.deliveredShare ?? '—'} | ${r.previousShare ?? '—'} |`);
}

L.push('', '## 4. Within-family comparison (corrected)', '');
for (const [behaviour, list] of Object.entries(families)) {
  const p = median(list.map(r => r.potential));
  L.push(`### ${behaviour} — ${list.length} fighters`, '',
    `Potential median **${p.toFixed(2)}** (was ${median(list.map(r => r.previousPotential)).toFixed(2)} before the grab correction).`, '',
    '| Identity | Potential | vs family | Guaranteed floor | Exposure | Delivered % | Flag |',
    '| --- | --- | --- | --- | --- | --- | --- |');
  for (const r of list) {
    const flags = [r.outlier ? 'potential outlier' : '', r.measured?.far > 0 ? 'hits past reach' : '']
      .filter(Boolean).join(' · ');
    L.push(`| ${r.id} | ${r.potential} | ${r.vsFamily}x | ${r.guaranteed} | ${r.exposure} | ${r.deliveredShare ?? '—'} | ${flags || '—'} |`);
  }
  L.push('');
}

const outliers = rows.filter(r => r.outlier);
L.push('## 5. What the corrected table shows', '',
  `- Within-family outliers: ${outliers.length ? outliers.map(r => `${r.id} (${r.vsFamily}x, ${r.potential})`).join(', ') : 'none'}.`,
  '- The grab family\'s ceiling is now 40 / 36 / 38. At point blank all three delivered exactly that,',
  '  so the family is not damage-starved; it loses delivery with distance.',
  '- Median potentials by family, corrected: '
    + Object.entries(families).map(([b, l]) => `${b} ${median(l.map(r => r.potential)).toFixed(1)}`).join(', ') + '.',
  '', '## 6. Not concluded', '',
  'No fighter is called overpowered or underpowered here. Potential is a ceiling, not an expectation:',
  'it ignores blocking, movement, cover and the opponent\'s own ultimate. The measured columns show what',
  'landed against a stationary or single-behaviour opponent at three fixed distances.', '');

writeFileSync(resolve(outDir, 'ULTIMATE_BALANCE_CORRECTED.md'), L.join('\n'));
writeFileSync(resolve(outDir, 'ultimate-balance-corrected.json'), JSON.stringify({
  generatedAt: new Date().toISOString(),
  methodology: {
    potential: 'sum of damaging events at ceiling; grab counts hits - 1 because event 0 is the pull',
    nonDamaging: NON_DAMAGING,
    preservedBaseline: 'artifacts/dev/phase29/BALANCE_AUDIT.md'
  },
  families: Object.fromEntries(Object.entries(families).map(([b, l]) => [b, {
    fighters: l.length, medianPotential: +median(l.map(r => r.potential)).toFixed(2)
  }])),
  fighters: rows
}, null, 2));
console.log(`corrected balance: ${rows.length} fighters, ${outliers.length} family outliers`);
console.log('grab ceilings:', rows.filter(r => r.behaviour === 'grab')
  .map(r => `${r.id} ${r.previousPotential}->${r.potential}`).join(', '));
