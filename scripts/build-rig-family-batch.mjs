// Build the runtime registry for the exact 19-bone animation family.
//
// The audit is the authority for membership. This script only promotes that result into a
// static module so the browser does not have to fetch a JSON file before the first animation
// frame, and it refuses to write a registry that disagrees with the audit or with the 17-clip
// contract.
//
//   npm run build:rig-batch
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const audit = JSON.parse(readFileSync(resolve(root, 'artifacts/rig-audit.json'), 'utf8'));
const group = (audit.groups || []).find(entry => entry.id === 'rig-19-14732939');
if (!group) throw new Error('rig-19-14732939 is missing from artifacts/rig-audit.json');
if (group.joints !== 19) throw new Error(`expected 19 joints, got ${group.joints}`);
if (group.size !== 55) throw new Error(`expected 55 members, got ${group.size}`);
if (!group.hasCore) throw new Error('the shared family is missing a core animation role');

export const SHARED_RIG_CLIPS = Object.freeze([
  'beam', 'block', 'charge', 'dodge', 'fly', 'get_up', 'heavy_punch', 'hit_light',
  'idle', 'jab', 'jump', 'knockdown', 'land', 'launcher', 'run', 'sprint', 'walk'
]);

const clipSet = new Set(group.sharedClipNames || []);
const missingFromGroup = SHARED_RIG_CLIPS.filter(name => !clipSet.has(name));
if (missingFromGroup.length) {
  throw new Error('the audit family does not share all 17 clips: ' + missingFromGroup.join(', '));
}

const members = [...group.members]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(member => {
    if (member.error) throw new Error(`${member.name} is unresolved: ${member.error}`);
    if (member.missingCore?.length) throw new Error(`${member.name} is missing core roles: ${member.missingCore.join(', ')}`);
    if (!member.url) throw new Error(`${member.name} has no resolved body URL`);
    const native = new Set(member.clipNames || []);
    const absent = SHARED_RIG_CLIPS.filter(name => !native.has(name));
    if (absent.length) throw new Error(`${member.name} is missing shared clips: ${absent.join(', ')}`);
    return Object.freeze({ name: member.name, key: member.slug, url: member.url });
  });

const source = members.find(member => member.key === 'kaze');
if (!source) throw new Error('the shared family has no Kaze source body');
const sourceEntry = group.members.find(member => member.slug === 'kaze');
if (sourceEntry.clips !== 17) {
  throw new Error(`the shared source must carry exactly the 17 common clips; it carries ${sourceEntry.clips}`);
}
if (new Set(members.map(member => member.url)).size !== members.length) {
  throw new Error('two shared-family members mount the same body URL');
}

const payload = {
  id: group.id,
  joints: group.joints,
  sharedClipCount: SHARED_RIG_CLIPS.length,
  source: source.url,
  clips: SHARED_RIG_CLIPS,
  members
};

const lines = [
  '// Generated by scripts/build-rig-family-batch.mjs from artifacts/rig-audit.json.',
  '// Do not hand-edit: rerun `npm run build:rig-batch` after the rig audit changes.',
  '',
  `export const SHARED_RIG_FAMILY_ID = ${JSON.stringify(payload.id)};`,
  `export const SHARED_RIG_FAMILY_JOINTS = ${payload.joints};`,
  `export const SHARED_RIG_FAMILY_SOURCE = ${JSON.stringify(payload.source)};`,
  `export const SHARED_RIG_CLIPS = Object.freeze(${JSON.stringify(payload.clips)});`,
  `export const SHARED_RIG_FAMILY = Object.freeze({`,
  `  id: SHARED_RIG_FAMILY_ID,`,
  `  joints: SHARED_RIG_FAMILY_JOINTS,`,
  `  source: SHARED_RIG_FAMILY_SOURCE,`,
  `  clips: SHARED_RIG_CLIPS,`,
  `  members: Object.freeze([`,
  ...members.map(member => `    Object.freeze({ name: ${JSON.stringify(member.name)}, key: ${JSON.stringify(member.key)}, url: ${JSON.stringify(member.url)} }),`),
  `  ])`,
  `});`,
  ''
];
mkdirSync(resolve(root, 'public/js/anim'), { recursive: true });
writeFileSync(resolve(root, 'public/js/anim/shared_rig_family_data.js'), lines.join('\n'));
console.log(JSON.stringify({
  file: 'public/js/anim/shared_rig_family_data.js',
  family: payload.id,
  members: members.length,
  clips: SHARED_RIG_CLIPS.length,
  source: source.name,
  sourceUrl: source.url
}, null, 2));
