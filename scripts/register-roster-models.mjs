// Register every generated roster body in public/models/characters/manifest.json.
//
//   node scripts/register-roster-models.mjs
//
// public/js/human_fighter.js loads a fighter's model by slugging its identity (\"Iron Man (Tony
// Stark)\" -> iron_man_tony_stark) and looking that key up in this manifest. An entry that is absent
// or carries `enabled: false` is skipped and the fighter silently keeps its runtime fallback body,
// which is how the roster ended up on primitive assemblies in the first place. So the manifest is
// the switch that decides whether a generated body is actually used, and it is written here rather
// than by hand so it can never drift from what is on disk.
//
// Each entry records the honest provenance: these are ORIGINAL stylised bodies authored by
// assets/blender/build_roster_fighters.py in this repository. They are not licensed character
// models, and the manifest says so, along with the exact file that would replace each one if a
// licensed source were ever supplied.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const MANIFEST = resolve(ROOT, 'public/models/characters/manifest.json');
const ROSTER_DIR = resolve(ROOT, 'public/models/characters/roster');

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
manifest.characters ||= {};

const GENERATOR = 'assets/blender/build_roster_fighters.py';
const SOURCE = `Original stylised body authored in this repository by ${GENERATOR} ` +
  '(Blender lofted geometry, skinned to a 19-bone armature, eight clips).';
const LICENCE = 'Original work generated by this repository\'s own script ' +
  '(no third-party model, texture or scan)';
const PENDING = {
  goku: '/models/characters/goku/Goku.fbx',
  iron_man_tony_stark: '/models/characters/iron-man-mark-v-rig/Iron Man Mark V Rig Materials.gltf',
  iron_spider: '/models/characters/iron_spider/iron_spider.glb'
};

const files = existsSync(ROSTER_DIR)
  ? readdirSync(ROSTER_DIR).filter(name => name.endsWith('.glb')).sort()
  : [];

if (files.length === 0) {
  console.error('No roster GLBs found in ' + ROSTER_DIR +
    '; run: npm run build:roster-fighters');
  process.exit(1);
}

let added = 0;
let updated = 0;
for (const file of files) {
  const slug = file.replace(/\.glb$/, '');
  const bytes = statSync(resolve(ROSTER_DIR, file)).size;
  const existing = manifest.characters[slug];
  const entry = {
    url: `/models/characters/roster/${file}`,
    format: 'gltf',
    enabled: true,
    yawOffset: 0,
    assetKind: 'original-alternative',
    source: SOURCE,
    creator: 'Browser Smash project',
    license: LICENCE,
    pendingLicensedAsset: PENDING[slug]
      ? `${PENDING[slug]} (not supplied; this original body stands in until it is)`
      : undefined,
    notes: 'ORIGINAL stylised body generated by the shared Blender kernel that produces the ' +
      'reference fighter Kaze: the same lofted anatomy, layered garments with measured clearance ' +
      'between layers, a 19-bone armature, hybrid skin weights and eight clips (idle, walk, run, ' +
      'jump, jab, heavy_punch, block, hit_light). It is not a licensed character model: that source ' +
      'has never been supplied and unlicensed copies are not used. Regenerate with ' +
      '`npm run build:roster-fighters`; validate with `npm run test:roster-models`. ' +
      'The garment layer, head treatment, hair silhouette, palette and build are per-fighter; the ' +
      'anatomy underneath is shared with Kaze.',
    verified: {
      bytes,
      inspectedWith: `node scripts/inspect-character-glb.mjs public/models/characters/roster/${file}`,
      rosterTest: 'npm run test:roster-models'
    }
  };
  if (entry.pendingLicensedAsset === undefined) delete entry.pendingLicensedAsset;
  if (existing) updated++; else added++;
  manifest.characters[slug] = entry;
}

// The first generation of these three exports is kept on the record rather than deleted.
//
// Those files (assets/blender/build_roster_models.py) are real rigs, but they render worse than
// the authored bodies in public/js/characters/sculpted.js - sphere shoulders and knees, and the
// undershirt shell z-fighting across the chest - so they stay disabled and keep the reason they
// are off. scripts/test-animation-pipeline.mjs asserts exactly that, and dropping the entries
// would throw the finding away, along with the note about which licensed source each stands in
// for. The fighter's active entry is the validated roster body written above.
const SUPERSEDED = [
  { key: 'goku-alt', fighter: 'goku', file: 'goku-alt.glb', pending: PENDING.goku },
  { key: 'iron-man-alt', fighter: 'iron_man_tony_stark', file: 'iron-man-alt.glb', pending: PENDING.iron_man_tony_stark },
  { key: 'iron-spider-alt', fighter: 'iron_spider', file: 'iron-spider-alt.glb', pending: PENDING.iron_spider }
];
for (const item of SUPERSEDED) {
  const supersededPath = resolve(ROOT, 'public/models/characters/original', item.file);
  if (!existsSync(supersededPath)) continue;
  manifest.characters[item.key] = {
    url: `/models/characters/original/${item.file}`,
    format: 'gltf',
    enabled: false,
    yawOffset: 0,
    assetKind: 'original-alternative',
    source: 'Original stylised body authored in this repository by assets/blender/build_roster_models.py',
    creator: 'Browser Smash project',
    license: LICENCE,
    pendingLicensedAsset: item.pending,
    notes: 'SUPERSEDED and disabled on purpose: this export from the earlier roster generator ' +
      'renders worse than the body that replaced it (sphere shoulders and knees, and the ' +
      'undershirt shell z-fighting across the chest), so it is retained only as the record of ' +
      `that finding. The active, validated body for this fighter is /models/characters/roster/${item.fighter}.glb.`,
    verified: {
      bytes: statSync(supersededPath).size,
      rendersWorseThan: 'public/js/characters/sculpted.js',
      supersededBy: `/models/characters/roster/${item.fighter}.glb`
    }
  };
}

manifest.version = 2;
manifest.roster = {
  generator: GENERATOR,
  rebuild: 'npm run build:roster-fighters',
  validate: 'npm run test:roster-models',
  count: files.length,
  // The launch contract is frozen at 38; `count` is the generated-export inventory, not the roster.
  launchCount: 38,
  note: `${files.length} generated roster exports are retained in public/models/characters/roster. ` +
    'The authoritative launch roster is 38 and also includes imported HD bodies, so not every ' +
    'selectable fighter uses a generated GLB. Kaze keeps the reference export from ' +
    'assets/blender/build_anime_fighter.py.'
};

writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
console.log(`manifest: ${added} added, ${updated} updated, ${files.length} roster bodies enabled`);
