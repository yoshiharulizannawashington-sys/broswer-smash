// Phase 29 ultimate audit: what each of the 34 playable identities actually does at runtime.
// Reads the real moveset data, the behaviour implementations' declared event plans, and the two
// presentation layers that exist (cinematic finishers, authored ultimate clips).
import { readFileSync, writeFileSync } from 'node:fs';
import { MOVESETS } from '../public/js/combat/movesets.js';
import { FINISHERS } from '../public/js/combat/cinematic_finisher.js';
import { CLIP_SPECS } from '../public/js/anim/clip_library.js';

// The choreography module owns the identity->clip map (SIGNATURE_CLIP). Read it from source rather
// than re-deriving a prefix match: `iron_man_tony_stark` does not start with `iron_man_repulsor`,
// so prefix matching silently reported one authored clip instead of two.
const choreoSource = readFileSync(new URL('../public/js/combat/ultimate_choreography.js', import.meta.url), 'utf8');
const SIGNATURE_CLIP = {};
for (const m of choreoSource.matchAll(/([a-z0-9_]+):\s*'([a-z0-9_]+)'/g)) {
  if (CLIP_SPECS[m[2]]) SIGNATURE_CLIP[m[1]] = m[2];
}

const BEHAVIOUR_MECHANICS = {
  beam: ['lane', 'Single lane from the hands along the cast direction, stops at cover, damage falls off with distance (min 55%), width-gated dodge'],
  rush: ['contact chain', 'One contact per hit, each needs range + line of sight; the owner steps in behind every landed hit'],
  slam: ['radial', 'Real leap on cast (velocity 8.6 up), radial landing inside the mark; the leap is avoidable'],
  storm: ['marked strikes', 'Strikes land on the mark where the target stood at cast; the marks do not track'],
  zone: ['ticks', 'Persistent field at one point on the ground, damages in ticks, does not follow'],
  grab: ['contact chain', 'A pull that must connect, then a short finishing chain on the held target'],
  barrage: ['contact chain', 'Aimed shells: each needs line of sight and range, fired from the owner']
};

const rows = Object.entries(MOVESETS).map(([id, v]) => {
  const u = v.ultimate || {};
  return {
    id, label: u.label, behaviour: u.behaviour,
    damage: u.damage, hits: u.hits ?? u.ticks ?? null, radius: u.radius ?? null, range: u.range ?? null,
    width: u.width ?? null, kbs: u.kbs, launchY: u.launchY, stun: u.stun,
    startup: u.startup, active: u.active, recovery: u.recovery,
    total: +((u.startup || 0) + (u.active || 0) + (u.recovery || 0)).toFixed(2),
    note: u.note || '',
    finisher: Boolean(FINISHERS[id]),
    // The choreography keys its map by the short name (`iron_man`), not the roster slug
    // (`iron_man_tony_stark`), so resolve by prefix as well as exact match.
    clip: SIGNATURE_CLIP[id]
      || Object.entries(SIGNATURE_CLIP).find(([k]) => id === k || id.startsWith(k + '_'))?.[1]
      || null,
    aura: v.form?.aura || 'none', specialType: v.form?.special?.type || null
  };
});
const byBehaviour = {};
for (const r of rows) (byBehaviour[r.behaviour] ||= []).push(r);

const L = [];
L.push('# Phase 29 — ultimate runtime audit', '',
  'Generated by `scripts/phase29-ultimate-audit.mjs` from `combat/movesets.js`, `combat/cinematic_finisher.js`',
  'and `anim/clip_library.js`. Design proposals live in `DESIGN.md`, not here.', '',
  '## 1. Counts', '',
  '| Source | Count | Meaning |', '| --- | --- | --- |',
  `| playable roster (\`main.js\`) | **${rows.length}** | launch identities, all audited below |`,
  '| `allRoster` in `main.js` | 59 | 34 selectable + 25 DLC names with no moveset, no locomotion and no body — the 59 target is real, 25 of it is unbuilt |',
  '| online catalogue (`roster.json`) | 50 | separate namespace, not playable identities |',
  '| model/weapon manifest | 66 records, 63 enabled | asset records, several per character |', '',
  '## 2. The seven runtime behaviours', '',
  '| Behaviour | Fighters | Event model | What actually happens |', '| --- | --- | --- | --- |');
for (const [b, list] of Object.entries(byBehaviour)) {
  const [model, text] = BEHAVIOUR_MECHANICS[b] || ['?', '?'];
  L.push(`| ${b} | ${list.length} | ${model} | ${text} |`);
}
L.push('', '## 3. Per-fighter matrix', '',
  '| # | Identity | Ultimate | Behaviour | Dmg | Hits/ticks | Radius | Range | Startup/active/recovery | Total | Finisher | Authored clip |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
rows.forEach((r, i) => L.push(`| ${String(i + 1).padStart(2, '0')} | ${r.id} | ${r.label} | ${r.behaviour} | ${r.damage} | ${r.hits ?? '—'} | ${r.radius ?? '—'} | ${r.range} | ${r.startup}/${r.active}/${r.recovery} | ${r.total}s | ${r.finisher ? 'yes' : '**no**'} | ${r.clip ? '`' + r.clip + '`' : '**none**'} |`));

L.push('', '## 4. Findings', '');
const all = rows.map(r => r.damage).sort((a, b) => a - b);
L.push(`- **Seven behaviours cover 34 fighters.** rush 9, storm 8, zone 7, beam 4, grab 3, slam 2, barrage 1.`);
L.push(`- **Ultimate damage across the whole roster is ${all[0]}–${all[all.length - 1]}, median ${all[Math.floor(all.length / 2)]}.** The rush class alone spans ${Math.min(...byBehaviour.rush.map(r => r.damage))}–${Math.max(...byBehaviour.rush.map(r => r.damage))}, so two fighters with the same experience can differ fourfold in output.`);
L.push(`- **Only ${rows.filter(r => r.finisher).length} of ${rows.length} identities have an authored cinematic finisher** (\`${rows.filter(r => r.finisher).map(r => r.id).join(', ')}\`). The other ${rows.length - rows.filter(r => r.finisher).length} cast the same behaviour with no camera language at all.`);
const clipCount = rows.filter(r => r.clip).length;
L.push(`- **Only ${clipCount} ${clipCount === 1 ? 'identity has' : 'identities have'} an authored ultimate clip** (\`${rows.filter(r => r.clip).map(r => r.clip).join('`, `')}\`). Every other ultimate is performed with the shared generic clips plus the choreography overlay's static beat poses.`);
L.push('- Within a behaviour the differences are numbers, not experience: radius, range, damage, timing. A player cannot tell two `rush` ultimates apart except by how much health they lost.');
L.push('- The behaviours are honest about misses (out-of-lane, outside-width, cover, out-of-range) and refund the meter when interrupted before the first hit. That part is sound and should be preserved by any redesign.');
L.push('', '## 5. Correction to the Phase 28 audit', '',
  'The Phase 28 identity audit reported `withCinematicUltimate: 0`. That check looked for a `cinematic` field on the',
  'moveset data. No moveset carries that field — but seven identities do have authored finisher camera sequences in',
  '`combat/cinematic_finisher.js`. The correct statement is **7 of 34 have authored finisher camera work**, not zero.', '');

writeFileSync('artifacts/dev/phase29/ULTIMATE_AUDIT.md', L.join('\n') + '\n');
console.log(L.slice(L.indexOf('## 4. Findings') + 1, L.length - 6).join('\n'));
console.log('\nwrote artifacts/dev/phase29/ULTIMATE_AUDIT.md');
